function keycaps() {
  const letters = ['q', 'w', 'e', 'r', 't', 'y', 'u', 'i', 'o', 'p', 'a', 's', 'd', 'f', 'g', 'h', 'j', 'k', 'l', 'z', 'x', 'c', 'v', 'b', 'n', 'm'];
  const digits = ['1', '2', '3', '4', '5', '6', '7', '8', '9', '0'];
  const named = [
    { key: 'ArrowUp', label: 'Up' }, { key: 'ArrowDown', label: 'Down' },
    { key: 'ArrowLeft', label: 'Left' }, { key: 'ArrowRight', label: 'Right' },
    { key: 'Enter', label: 'Enter' }, { key: ' ', label: 'Space' }, { key: 'Escape', label: 'Esc' },
  ];
  return digits.map((k) => ({ key: k, label: k }))
    .concat(letters.map((k) => ({ key: k, label: k.toUpperCase() })))
    .concat(named);
}

