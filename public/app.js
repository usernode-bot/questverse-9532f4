// Every genre a built-in title carries, in the order the titles list them, so
// the filter tags read like the shelf they filter.
function genreTags() {
  const out = [];
  for (const title of TITLES) {
    for (const genre of title.genres) if (!out.includes(genre)) out.push(genre);
  }
  return out;
}

