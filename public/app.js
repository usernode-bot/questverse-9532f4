async function removeEntry(entry) {
  try {
    await removeCatalogueEntry(entry.id);
    rig.catalogue = rig.catalogue.filter((e) => e.id !== entry.id);
    toast('Removed ' + entry.title + ' from the collection.');
    render();
  } catch (err) {
    toast(apiMessage(err, 'Could not remove that entry.'));
  }
}

