      unlockAudio();
      tone('tick');
      const strip = document.querySelector('[data-cover-strip]');
      const card = document.querySelector('[data-cover="' + title.id + '"]');
      if (strip && card) strip.scrollTo({ left: card.offsetLeft - strip.offsetLeft, behavior: 'smooth' });
