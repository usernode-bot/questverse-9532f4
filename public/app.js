let toastTimer = null;
// The platform's native kit owns the toast idiom (a capsule that never steals
// a tap). The app's own element is the fallback for a load without the kit.
function toast(message) {
  if (window.unNative && typeof window.unNative.toast === 'function') {
    try { window.unNative.toast(message); return; } catch { /* fall through */ }
  }
  const node = document.getElementById('toast');
  if (!node) return;
  node.textContent = message;
  node.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { node.hidden = true; }, 2600);
}

function apiMessage(err, fallback) {
  if (err instanceof ApiError) {
    if (err.status === 401) return 'Open this rig inside Homeroom to use it.';
    return err.message || fallback;
  }
  return fallback;
}

// The rig's clock reads through the platform (usernode.now()), so a preview
// opened at a chosen moment shows that moment. It is only ever displayed.
function nowDate() {
  try {
    if (window.usernode && typeof window.usernode.now === 'function') return window.usernode.now();
  } catch { /* fall back to the device clock */ }
  return new Date();
}

function clockText() {
  const d = nowDate();
  const pad = (n) => (n < 10 ? '0' + n : String(n));
  return pad(d.getHours()) + ':' + pad(d.getMinutes());
}

let clockTimer = null;
function startClock() {
  if (clockTimer) return;
  clockTimer = setInterval(() => {
    const text = clockText();
    for (const node of document.querySelectorAll('[data-clock]')) node.textContent = text;
  }, 20000);
}

function formatBytes(bytes) {
  const n = Number(bytes);
  if (!Number.isFinite(n) || n <= 0) return '0 KB';
  if (n < 1024) return Math.round(n) + ' B';
  if (n < 1024 * 1024) return Math.round(n / 1024) + ' KB';
  return (n / (1024 * 1024)).toFixed(1) + ' MB';
}

function formatWhen(value) {
  const d = value ? new Date(value) : null;
  if (!d || Number.isNaN(d.getTime())) return 'saved earlier';
  return d.toLocaleDateString([], { day: 'numeric', month: 'short' });
}

function go(hash) {
  if (window.location.hash === hash) render();
  else window.location.hash = hash;
}

function parseHash() {
  const raw = window.location.hash.replace(/^#/, '') || '/';
  const qIndex = raw.indexOf('?');
  const path = qIndex >= 0 ? raw.slice(0, qIndex) : raw;
  const query = qIndex >= 0 ? raw.slice(qIndex + 1) : '';
  return { parts: path.split('/').filter(Boolean), params: new URLSearchParams(query) };
}

