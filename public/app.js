async function saveMapping(message) {
  try {
    const saved = await saveBindings(rig.bindings);
    if (saved && Object.keys(saved).length) {
      const merged = Object.assign({}, DEFAULT_BINDINGS);
      for (const k of Object.keys(DEFAULT_BINDINGS)) if (typeof saved[k] === 'string' && saved[k]) merged[k] = saved[k];
      rig.bindings = merged;
    }
    toast(message || 'Joystick mapping saved.');
  } catch (err) {
    toast(apiMessage(err, 'Could not save the mapping.'));
  }
  render();
}

function assignKey(action, key) {
  if (!key) return;
  const clashes = conflictsFor(rig.bindings, action, key);
  if (clashes.length) {
    captureAction = null;
    toast(keyLabel(key) + ' is already ' + clashes[0] + '.');
    render();
    return;
  }
  rig.bindings[action] = key;
  captureAction = null;
  saveMapping(keyLabel(key) + ' is now ' + (ACTIONS.find((a) => a.key === action) || {}).label + '.');
}

